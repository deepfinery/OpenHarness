// The catalog of FMP datasets the Dataset tab can sync. Each entry is a pure data
// definition; datasetSync.ts runs them generically. Adding a dataset = adding an entry.
export type DatasetScope = 'market' | 'feed' | 'per-symbol';
// timeseries: dated history pulled with from/to and a moving cursor (append, idempotent).
// window:     a rolling date window re-pulled each run (calendars), chunked to dodge row caps.
// snapshot:   current values re-fetched and upserted in place (profiles, consensus, latest feeds).
export type IncrementalMode = 'timeseries' | 'window' | 'snapshot';

export interface DatasetDef {
  id: string;
  label: string;
  category: 'Prices' | 'Fundamentals' | 'Estimates' | 'Ownership' | 'Calendars' | 'Market' | 'Reference';
  description: string;
  endpoint: string; // FMP stable endpoint path
  scope: DatasetScope;
  incremental: IncrementalMode;
  keyFields: string[]; // upsert identity
  snapshotDated?: boolean; // append one row per sync (adds snapshot_date to the key)
  dateField?: string; // enables retention + timeseries cursoring
  supportsDateRange: boolean; // accepts from/to
  perSymbol: boolean; // iterate the universe (or an explicit list)
  paginated?: boolean; // feed endpoints paged with page/limit
  fixedSymbols?: string[]; // market datasets that still pull per fixed symbol (indexes)
  params?: Record<string, string | number>; // constant query params (period, etc.)
  defaultCollection: string;
  recommendedEveryMinutes: number;
}

